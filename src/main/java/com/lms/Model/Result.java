package com.lms.Model;

public class Result 
{
    private int rid;
    private int sid;
    private int eid;
    private int score;
    private int total_marks;

    public int getRid()
    {
        return rid;
    }

    public void setRid(int rid)
    {
        this.rid = rid;
    }

    public int getSid()
    {
        return sid;
    }

    public void setSid(int sid)
    {
        this.sid = sid;
    }

    public int getEid()
    {
        return eid;
    }

    public void setEid(int eid)
    {
        this.eid = eid;
    }

    public int getScore()
    {
        return score;
    }

    public void setScore(int score)
    {
        this.score = score;
    }

    public int getTotal_marks()
    {
        return total_marks;
    }

    public void setTotal_marks(int total_marks)
    {
        this.total_marks = total_marks;
    }
}